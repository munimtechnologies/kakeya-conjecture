"""The field F_{3^n} laid on the points of F_3^n, and linear groups coming from it.

A point x of F_3^n is stored as the integer sum c_i 3^i, where (c_0, ..., c_{n-1}) are its
coordinates; the same digits are the coefficients of a polynomial in F_3[t] / (f), with f a
primitive polynomial of degree n.  Field addition is coordinate addition, so lines of F_3^n
are lines of the field's additive group, and every map below is F_3-linear:

  * m_a : x -> a x            (multiplication by a nonzero field element),
  * phi : x -> x^3            (Frobenius).

H_r is the subgroup of order r of the multiplicative group (r divides 3^n - 1), generated by
g^((3^n - 1) / r) with g a primitive element; F_f is the subgroup of order f of the Galois
group <phi> (f divides n), generated by phi^(n / f).  G(r, f) = H_r F_f has order r f.
A set K that is a union of G-orbits contains a line in direction d iff it contains a line in
direction g d for all g in G, so only one direction per G-orbit has to be checked.
"""
import itertools


def digits(x, n):
    return tuple((x // 3 ** i) % 3 for i in range(n))


def from_digits(c):
    return sum(v * 3 ** i for i, v in enumerate(c))


def _addtab(k):
    base = 3 ** k
    digs = [digits(x, k) for x in range(base)]
    t = [0] * (base * base)
    for x in range(base):
        dx = digs[x]
        for y in range(base):
            dy = digs[y]
            t[x * base + y] = sum(((a + b) % 3) * 3 ** i for i, (a, b) in enumerate(zip(dx, dy)))
    return t


def _times_t(c, f):
    """c(t) * t mod f(t), where f = t^n + f_{n-1} t^{n-1} + ... + f_0 (f given as f_0..f_{n-1})."""
    n = len(c)
    top = c[n - 1]
    out = [0] + list(c[:-1])
    if top:
        out = [(out[i] - top * f[i]) % 3 for i in range(n)]
    return out


def find_primitive(n):
    """First (lexicographic) monic primitive polynomial of degree n over F_3 and the table
    exp[i] = t^i (as point integers), i = 0 .. 3^n - 2."""
    q = 3 ** n
    for f in itertools.product(range(3), repeat=n):
        if f[0] == 0:
            continue
        c = [1] + [0] * (n - 1)
        exp = [from_digits(c)]
        ok = True
        for i in range(1, q - 1):
            c = _times_t(c, f)
            e = from_digits(c)
            if e == 1:
                ok = False
                break
            exp.append(e)
        if not ok:
            continue
        c = _times_t(c, f)
        if from_digits(c) == 1 and len(set(exp)) == q - 1:
            return list(f), exp
    raise RuntimeError("no primitive polynomial found for n=%d" % n)


class Field:
    def __init__(self, n):
        self.n = n
        self.q = 3 ** n
        self.poly, self.exp = find_primitive(n)
        self.log = [-1] * self.q
        for i, e in enumerate(self.exp):
            self.log[e] = i
        s = n // 2
        self.m = 3 ** s
        self.AH, self.AL = _addtab(n - s), _addtab(s)
        self.hb = 3 ** (n - s)

    def add(self, a, b):
        m, hb = self.m, self.hb
        ah, al = divmod(a, m)
        bh, bl = divmod(b, m)
        return self.AH[ah * hb + bh] * m + self.AL[al * m + bl]

    def neg(self, a):
        return from_digits(tuple((-c) % 3 for c in digits(a, self.n)))

    def mul(self, a, b):
        if a == 0 or b == 0:
            return 0
        return self.exp[(self.log[a] + self.log[b]) % (self.q - 1)]

    def power3(self, a, k):
        """a^(3^k)."""
        if a == 0:
            return 0
        return self.exp[(self.log[a] * pow(3, k, self.q - 1)) % (self.q - 1)]

    # ---- groups ----
    def generators(self, r, f):
        """Permutations of the q points generating G(r, f)."""
        q, n = self.q, self.n
        if (q - 1) % r or n % f:
            raise ValueError("bad group (r=%d, f=%d) for n=%d" % (r, f, n))
        gens = []
        if r > 1:
            h = self.exp[(q - 1) // r]
            gens.append([self.mul(h, x) for x in range(q)])
        if f > 1:
            k = n // f
            gens.append([self.power3(x, k) for x in range(q)])
        return gens


def orbits(q, gens):
    """Orbit id of every point and the member lists, for the group generated by `gens`."""
    orb = [-1] * q
    members = []
    for i in range(q):
        if orb[i] >= 0:
            continue
        o = len(members)
        orb[i] = o
        mem = [i]
        stack = [i]
        while stack:
            x = stack.pop()
            for pm in gens:
                y = pm[x]
                if orb[y] < 0:
                    orb[y] = o
                    mem.append(y)
                    stack.append(y)
        members.append(sorted(mem))
    return orb, members


def canon_dir(F, v):
    """Representative of the direction of v != 0 (v and -v = 2v give the same lines)."""
    w = F.neg(v)
    return v if v < w else w


def direction_orbits(F, gens):
    """One representative direction per G-orbit of directions, and the orbit sizes."""
    q = F.q
    dirs = sorted(set(canon_dir(F, v) for v in range(1, q)))
    seen = {}
    reps, sizes = [], []
    for d in dirs:
        if d in seen:
            continue
        o = len(reps)
        seen[d] = o
        stack = [d]
        cnt = 1
        while stack:
            x = stack.pop()
            for pm in gens:
                y = canon_dir(F, pm[x])
                if y not in seen:
                    seen[y] = o
                    cnt += 1
                    stack.append(y)
        reps.append(d)
        sizes.append(cnt)
    return reps, sizes, len(dirs)


def mask_bits(L):
    out = []
    while L:
        low = L & -L
        out.append(low.bit_length() - 1)
        L ^= low
    return out


def minimal_masks(masks):
    """Drop every mask that strictly contains another one of the set."""
    S = set(masks)
    out = []
    for L in S:
        bits = mask_bits(L)
        dominated = False
        for k in range(1, len(bits)):
            for sub in itertools.combinations(bits, k):
                if sum(1 << b for b in sub) in S:
                    dominated = True
                    break
            if dominated:
                break
        if not dominated:
            out.append(L)
    return sorted(out)


def line_masks(F, orb, reps):
    """For every representative direction, the minimal sets of orbits (as bit masks) whose
    union contains a whole line of that direction."""
    q = F.q
    out = []
    for d in reps:
        d2 = F.add(d, d)
        ms = set()
        for a in range(q):
            b = F.add(a, d)
            c = F.add(a, d2)
            ms.add((1 << orb[a]) | (1 << orb[b]) | (1 << orb[c]))
        out.append(minimal_masks(ms))
    return out
