def coordinate_sections(K, j):
    """Sections of K (in F_3^4) by the class x_j = t, as masks of F_3^3 (other coordinates kept
    in order)."""
    S = space(3)
    secs = [0, 0, 0]
    for p in K:
        rest = tuple(p[i] for i in range(4) if i != j)
        secs[p[j]] |= 1 << S.idx[rest]
    return secs


def quick_controls():
    """Fast end-to-end controls, run inside every cut test. Raises AssertionError on failure."""
    # 1. k_3 = 13 (Lev 2009) through the same pipeline one dimension down: no 12-point Kakeya set in
    #    F_3^3 under any cut allowed by (T), and some 13-point set.
    S2 = space(2)
    for cut in cuts_T(12, 2):
        for row in search_cut(S2, cut):
            assert row["found"] is None, ("12-point set in F_3^3?", cut, row)
    hits = []
    for cut in cuts_T(13, 2):
        hits += [r["found"] for r in search_cut(S2, cut) if r["found"] is not None]
    assert hits, "no 13-point Kakeya set found in F_3^3"
    for f in hits:
        assert f["valid"] and f["is_kakeya"] and f["size"] == 13, f
    # 2. Lev's 27-point set: Kakeya, and for every coordinate class and every order of its three
    #    sections, the C-search completes the first two within the size of the third.
    S3 = space(3)
    assert len(set(KNOWN27)) == 27 and is_kakeya(KNOWN27, 4)
    for j in range(4):
        secs = coordinate_sections(KNOWN27, j)
        for X, Y, Z in itertools.permutations(secs):
            assert valid_ABC(S3, X, Y, Z)
            C = solve_AB(S3, X, Y, Z.bit_count())
            assert C is not None and C.bit_count() <= Z.bit_count(), (j, X, Y, Z)
            assert valid_ABC(S3, X, Y, C)
    return True
