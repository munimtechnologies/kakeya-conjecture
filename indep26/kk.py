"""
Second, independent implementation of the 26-point search (written without reusing kcut/ or gate26/
code). It covers TEN hyperplane cuts, derived from the product identity and the pair-product bound
(T) alone, so it does not depend on the sum-difference lemma of moments/SD.md. See indep26/README.md.

Conventions. A Kakeya set K in F_3^(m+1) is cut by the hyperplane class t = last coordinate into
three sections A (t = 0), B (t = 1), C (t = 2), each a subset of F_3^m. K is Kakeya if and only if
  (X) for every v in F_3^m there is x in A with x + v in B and x + 2v in C
      (the 3^m directions (v, 1)), and
  (D) for each of the (3^m - 1)/2 directions d of F_3^m, A, B or C contains a line of direction d.
Points of F_3^m are integers p = sum x_i 3^i; subsets are bit masks.
"""
import itertools
from math import comb

# ----------------------------------------------------------------------------------------------
# The space F_3^m


class Space:
    def __init__(self, m):
        self.m = m
        self.N = N = 3 ** m
        self.vec = [tuple((p // 3 ** i) % 3 for i in range(m)) for p in range(N)]
        self.idx = {v: p for p, v in enumerate(self.vec)}
        vec, idx = self.vec, self.idx
        self.add = [[idx[tuple((x + y) % 3 for x, y in zip(vec[p], vec[q]))] for q in range(N)]
                    for p in range(N)]
        # sub[p][q] = p - q
        self.sub = [[idx[tuple((x - y) % 3 for x, y in zip(vec[p], vec[q]))] for q in range(N)]
                    for p in range(N)]
        self.dirs = [d for d in range(1, N) if [t for t in vec[d] if t][0] == 1]
        self.lines_by_dir = []
        for d in self.dirs:
            seen = []
            for p in range(N):
                q = self.add[p][d]
                r = self.add[q][d]
                mk = (1 << p) | (1 << q) | (1 << r)
                if mk not in seen:
                    seen.append(mk)
            self.lines_by_dir.append(tuple(seen))


_SPACES = {}


def space(m):
    if m not in _SPACES:
        _SPACES[m] = Space(m)
    return _SPACES[m]


def bits(mask):
    out = []
    p = 0
    while mask:
        if mask & 1:
            out.append(p)
        mask >>= 1
        p += 1
    return out


def mask_of(points):
    mk = 0
    for p in points:
        mk |= 1 << p
    return mk


def dirs_with_line(S, mask):
    """Indices (into S.dirs) of the directions in which the set `mask` contains a full line."""
    return frozenset(i for i, L in enumerate(S.lines_by_dir) if any((l & mask) == l for l in L))


# ----------------------------------------------------------------------------------------------
# The affine group AGL(m, 3), by generators


def linear_generators(S):
    """Elementary transvections x_i += x_j (i != j) and the scaling x_0 -> 2 x_0, as point
    permutations. They generate GL(m, 3); test_controls checks the order of the generated group."""
    m = S.m
    mats = []
    for i in range(m):
        for j in range(m):
            if i != j:
                M = [[int(r == c) for c in range(m)] for r in range(m)]
                M[i][j] = 1
                mats.append(M)
    D = [[int(r == c) for c in range(m)] for r in range(m)]
    D[0][0] = 2
    mats.append(D)
    perms = []
    for M in mats:
        perms.append([S.idx[tuple(sum(M[i][j] * v[j] for j in range(m)) % 3 for i in range(m))]
                      for v in S.vec])
    return perms


def translation_generators(S):
    perms = []
    for i in range(S.m):
        e = S.idx[tuple(int(j == i) for j in range(S.m))]
        perms.append([S.add[p][e] for p in range(S.N)])
    return perms


def group_order(perms, N):
    """Order of the permutation group generated by `perms` (breadth-first closure)."""
    ident = tuple(range(N))
    seen = {ident}
    todo = [ident]
    gens = [tuple(g) for g in perms]
    while todo:
        h = todo.pop()
        for g in gens:
            gh = tuple(g[h[p]] for p in range(N))
            if gh not in seen:
                seen.add(gh)
                todo.append(gh)
    return len(seen)


def _tables(perm, N):
    """Three 512-entry tables so that image(mask) = T0[m & 511] | T1[(m >> 9) & 511] | T2[m >> 18]."""
    out = []
    for k in range(3):
        T = [0] * 512
        for s in range(512):
            r = 0
            for b in range(9):
                if (s >> b) & 1:
                    p = 9 * k + b
                    if p < N:
                        r |= 1 << perm[p]
            T[s] = r
        out.append(T)
    return tuple(out)


_ORBITS = {}


def orbit_reps(S, a):
    """One representative mask of every AGL(m,3)-orbit of a-subsets of F_3^m, with the orbit size,
    in a fixed order (first member in itertools.combinations order). The orbits partition all
    a-subsets by construction (each subset is marked when first reached)."""
    key = (S.m, a)
    if key in _ORBITS:
        return _ORBITS[key]
    assert S.N <= 27
    tabs = [_tables(g, S.N) for g in linear_generators(S) + translation_generators(S)]
    seen = set()
    reps = []
    for cmb in itertools.combinations(range(S.N), a):
        mk = 0
        for p in cmb:
            mk |= 1 << p
        if mk in seen:
            continue
        seen.add(mk)
        stack = [mk]
        size = 0
        while stack:
            x = stack.pop()
            size += 1
            x0 = x & 511
            x1 = (x >> 9) & 511
            x2 = x >> 18
            for T0, T1, T2 in tabs:
                y = T0[x0] | T1[x1] | T2[x2]
                if y not in seen:
                    seen.add(y)
                    stack.append(y)
        reps.append((mk, size))
    _ORBITS[key] = reps
    return reps


def orbit_of(S, mask):
    """The full AGL(m,3)-orbit of one set, as a Python set of masks."""
    tabs = [_tables(g, S.N) for g in linear_generators(S) + translation_generators(S)]
    seen = {mask}
    stack = [mask]
    while stack:
        x = stack.pop()
        x0 = x & 511
        x1 = (x >> 9) & 511
        x2 = x >> 18
        for T0, T1, T2 in tabs:
            y = T0[x0] | T1[x1] | T2[x2]
            if y not in seen:
                seen.add(y)
                stack.append(y)
    return seen


# ----------------------------------------------------------------------------------------------
# Middle sections B: every b-set containing the origin that meets every translate A + v


def enum_B(S, A, b):
    """All b-subsets B of F_3^m with 0 in B and B meeting A + v for every v (equivalently
    B - A = F_3^m), as masks in increasing lexicographic order of their point lists."""
    N = S.N
    FULL = (1 << N) - 1
    Apts = bits(A)
    a = len(Apts)
    cov = [0] * N
    for y in range(N):
        mk = 0
        for x in Apts:
            mk |= 1 << S.sub[y][x]      # y lies in A + v exactly for v = y - x
        cov[y] = mk
    suffix = [0] * (N + 1)
    for y in range(N - 1, -1, -1):
        suffix[y] = suffix[y + 1] | cov[y]
    out = []

    def rec(start, r, covered, Bm):
        if r == 0:
            if covered == FULL:
                out.append(Bm)
            return
        unc = FULL & ~covered
        if unc.bit_count() > a * r:
            return
        for y in range(start, N - r + 1):
            if unc & ~suffix[y]:
                return
            rec(y + 1, r - 1, covered | cov[y], Bm | (1 << y))

    if b >= 1:
        rec(1, b - 1, cov[0], 1)
    return out


# ----------------------------------------------------------------------------------------------
# Third sections C: exact branch and bound


def transversal_sets(S, A, B):
    """P[v] = mask of the points x + 2v with x in A and x + v in B. C must meet every P[v]."""
    P = [0] * S.N
    Apts = bits(A)
    for y in bits(B):
        sy = S.sub[y]
        ay = S.add[y]
        for x in Apts:
            v = sy[x]
            P[v] |= 1 << ay[v]          # y + v = x + 2v
    return P


def c_search(P, Rlines, c):
    """A set C with |C| <= c meeting every mask in P and containing a line from every tuple in
    Rlines, or None if there is none. Exact: every branch is a case split that some solution must
    take, and the bounds only discard partial sets that cannot be completed within c points."""
    for q in P:
        if q == 0:
            return None
    forced = 0
    for q in P:
        if (q & (q - 1)) == 0:
            forced |= q
    if forced.bit_count() > c:
        return None
    return _dfs(P, Rlines, c, forced, 0)


def _dfs(P, Rlines, c, C, excl):
    # Invariant: excl and C are disjoint; no point of excl may be added below this node.
    k = C.bit_count()
    best = 0
    bestn = 1 << 30
    used = 0
    lb = 0
    for q in P:
        if q & C:
            continue
        q2 = q & ~excl
        if q2 == 0:
            return None
        n = q2.bit_count()
        if n < bestn:
            bestn = n
            best = q2
        if (q2 & used) == 0:            # greedy packing of pairwise disjoint unmet sets
            used |= q2
            lb += 1
    if k + lb > c:
        return None
    dbest = None
    for lines in Rlines:
        done = False
        for l in lines:
            if (l & C) == l:
                done = True
                break
        if done:
            continue
        opts = [l for l in lines if (l & excl) == 0]
        if not opts:
            return None
        need = min((l & ~C).bit_count() for l in opts)
        if k + need > c:
            return None
        if dbest is None or len(opts) < len(dbest):
            dbest = opts
    if best == 0 and dbest is None:
        return C
    if best and (dbest is None or bestn <= len(dbest)):
        ex = excl
        q = best
        while q:
            low = q & -q
            r = _dfs(P, Rlines, c, C | low, ex)
            if r is not None:
                return r
            ex |= low
            q ^= low
        return None
    for l in dbest:
        if k + (l & ~C).bit_count() > c:
            continue
        r = _dfs(P, Rlines, c, C | l, excl)
        if r is not None:
            return r
    return None


def solve_AB(S, A, B, c, dirsA=None):
    """A third section C with |C| <= c completing (A, B) to a Kakeya set, or None."""
    P = transversal_sets(S, A, B)
    if dirsA is None:
        dirsA = dirs_with_line(S, A)
    covered = dirsA | dirs_with_line(S, B)
    Rlines = [L for i, L in enumerate(S.lines_by_dir) if i not in covered]
    return c_search(P, Rlines, c)


def valid_ABC(S, A, B, C):
    """Direct check of (X) and (D), written separately from the search."""
    Ap, Bp, Cp = set(bits(A)), set(bits(B)), set(bits(C))
    for v in range(S.N):
        if not any(S.add[x][v] in Bp and S.add[S.add[x][v]][v] in Cp for x in Ap):
            return False
    for L in S.lines_by_dir:
        if not any((l & A) == l or (l & B) == l or (l & C) == l for l in L):
            return False
    return True


# ----------------------------------------------------------------------------------------------
# Whole sets in F_3^n (tuples), checked by brute force


def is_kakeya(K, n):
    Ks = set(tuple(p) for p in K)
    for d in itertools.product(range(3), repeat=n):
        nz = [t for t in d if t]
        if not nz or nz[0] != 1:
            continue
        ok = False
        for p in Ks:
            q = tuple((x + y) % 3 for x, y in zip(p, d))
            r = tuple((x + 2 * y) % 3 for x, y in zip(p, d))
            if q in Ks and r in Ks:
                ok = True
                break
        if not ok:
            return False
    return True


def assemble(S, A, B, C):
    """The set of F_3^(m+1) with sections A, B, C at last coordinate 0, 1, 2."""
    K = []
    for t, X in enumerate((A, B, C)):
        for p in bits(X):
            K.append(S.vec[p] + (t,))
    return K


def class_sizes(K, n):
    """Section sizes (n0, n1, n2) for each of the (3^n - 1)/2 hyperplane classes of F_3^n."""
    out = []
    for xi in itertools.product(range(3), repeat=n):
        nz = [t for t in xi if t]
        if not nz or nz[0] != 1:
            continue
        cnt = [0, 0, 0]
        for p in K:
            cnt[sum(a * b for a, b in zip(xi, p)) % 3] += 1
        out.append(tuple(cnt))
    return out


def count_lines(K):
    Ks = sorted(set(tuple(p) for p in K))
    S = set(Ks)
    L = 0
    for i in range(len(Ks)):
        for j in range(i + 1, len(Ks)):
            z = tuple((-x - y) % 3 for x, y in zip(Ks[i], Ks[j]))
            if z in S and z > Ks[j]:
                L += 1
    return L


# ----------------------------------------------------------------------------------------------
# Which cuts must be searched


def cuts_T(N, m):
    """All sorted cuts (a, b, c) of N points whose pairwise products are >= 3^m (condition (T))."""
    out = []
    for a in range(N + 1):
        for b in range(a, N + 1):
            c = N - a - b
            if c >= b and a * b >= 3 ** m:
                out.append((a, b, c))
    return out


def cuts26_from_identity():
    """Cuts of 26 points in F_3^4 that the product identity forces (indep26/README.md):
    a class with (a-8)(b-8)(c-8) > 0, or (zero case) a class (a, 8, 18-a) with a <= 7."""
    out = []
    for (a, b, c) in cuts_T(26, 3):
        positive = (a - 8) * (b - 8) * (c - 8) > 0
        zero_case = 8 in (a, b, c) and a <= 7
        if positive or zero_case:
            out.append((a, b, c))
    return out


