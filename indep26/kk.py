# ----------------------------------------------------------------------------------------------
# The search for one cut


def search_cut(S, cut, part=0, parts=1, stop_at_first=True):
    """Exhaustive search for Kakeya sets with sections of sizes a, b, <= c (A an orbit
    representative, B through the origin), over the representatives with index = part mod parts.
    Returns one row per representative searched; row['found'] is None unless a set was found."""
    a, b, c = cut
    rows = []
    for i, (A, orb) in enumerate(orbit_reps(S, a)):
        if i % parts != part:
            continue
        dA = dirs_with_line(S, A)
        Bs = enum_B(S, A, b)
        found = None
        for B in Bs:
            C = solve_AB(S, A, B, c, dA)
            if C is not None:
                K = assemble(S, A, B, C)
                found = {"A": A, "B": B, "C": C, "size": len(K),
                         "valid": valid_ABC(S, A, B, C), "is_kakeya": is_kakeya(K, S.m + 1)}
                if stop_at_first:
                    break
        rows.append({"rep": i, "A": A, "orbit": orb, "nB": len(Bs), "found": found})
    return rows


